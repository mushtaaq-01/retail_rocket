export function getAllProducts() {
  return Object.entries(PRODUCT_CATALOG).map(([id, data]) => ({
    id,
    item_id: id,
    ...data
  }));
}

export function getCategories() {
  const categories = new Set();
  Object.values(PRODUCT_CATALOG).forEach((p) => {
    if (p.category) categories.add(p.category);
  });
  return Array.from(categories);
}

export function getBrands() {
  const brands = new Set();
  Object.values(PRODUCT_CATALOG).forEach((p) => {
    if (p.brand) brands.add(p.brand);
  });
  return Array.from(brands);
}

export function getPriceBounds() {
  const prices = Object.values(PRODUCT_CATALOG).map((p) => p.numericPrice || 0);
  return {
    min: Math.min(...prices),
    max: Math.max(...prices)
  };
}

export function enrichProduct(item) {
  if (!item) return null;
  const strId = String(item.item_id || item.id || "");
  const catalogEntry = PRODUCT_CATALOG[strId];

  return {
    ...item,
    id: strId,
    item_id: strId,
    name: item.name || catalogEntry?.name || `Product Item #${strId}`,
    category: item.category || catalogEntry?.category || "Consumer Retail",
    brand: item.brand || catalogEntry?.brand || "RetailBrand",
    price: item.price || catalogEntry?.price || "₹9,999",
    numericPrice: item.numericPrice || catalogEntry?.numericPrice || 9999,
    rating: item.rating || catalogEntry?.rating || 4.7,
    reviewsCount: item.reviewsCount || catalogEntry?.reviewsCount || 120,
    description: item.description || catalogEntry?.description || "High-performance consumer product designed for quality and reliability.",
    image: item.image || catalogEntry?.image || "https://images.unsplash.com/photo-1505740420928-5e560c06d30e?w=500&auto=format&fit=crop&q=80"
  };
}
